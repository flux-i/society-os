test('invitation handover, clipboard, all access choices, pending reissue and account pagination work', async ({ page, browser }) => {
  test.setTimeout(120000)
  await login(page)
  await navigate(page, 'Access & invitations')
  await expect(page.locator('.account-row')).not.toHaveCount(0)
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'], { origin: new URL(page.url()).origin })
  const numbers = ['201', '202', '203', '204', '301', '302', '303', '304', '401', '402', '403', '404', '501']
  let original = ''
  for (let index = 0; index < numbers.length; index++) {
    const role = ['RESIDENT', 'COMMITTEE', 'ADMINISTRATOR'][index % 3]
    await prepareInvitation(page, 'Demo Owner C-' + numbers[index], `interaction-${index}@browser.test`, role)
    const url = await issueLink(page)
    if (index === 0) {
      original = url
      await page.getByLabel('Personal link', { exact: true }).click()
      expect(await page.getByLabel('Personal link').evaluate((el: HTMLInputElement) => el.selectionEnd! - el.selectionStart!)).toBe(url.length)
      await page.getByRole('button', { name: 'Copy personal link', exact: true }).click()
      await expect(page.getByRole('button', { name: 'Link copied', exact: true })).toBeVisible()
      expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(url)
      await capture(page, 'invitation-copied')
    }
    if (index === 1) {
      await page.evaluate(() => { Object.defineProperty(navigator.clipboard, 'writeText', { configurable: true, value: () => Promise.reject(new Error('Simulated clipboard denial')) }) })
      await page.getByRole('button', { name: 'Copy personal link', exact: true }).click()
      await expect(page.getByRole('alert')).toContainText('Select and copy the link above.')
      await capture(page, 'invitation-clipboard-fallback')
    }
    await page.getByRole('button', { name: 'I’ve finished the handover', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Invite a person', exact: true })).toBeFocused()
  }
  await expect(page.getByRole('button', { name: 'Previous account page', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Next account page', exact: true }).click()
  await expect(page.getByText(/accounts · Page 2 of 2/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Next account page', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Previous account page', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Search accounts', exact: true }).fill('interaction-0@browser.test')
  await expect(page.locator('.account-row')).toHaveCount(1)
  await page.getByRole('button', { name: 'New invitation link', exact: true }).click()
  await page.getByRole('checkbox', { name: verifiedLabel }).check()
  await page.getByLabel('Verification note').fill('Reverified fictional identity to replace an invitation.')
  await issueLink(page)
  const recipientContext = await browser.newContext()
  try {
    const recipient = await recipientContext.newPage()
    await recipient.goto(original)
    await expect(recipient.getByRole('alert')).toContainText('expired or has already been used')
    await recipient.getByRole('button', { name: 'Return to sign in', exact: true }).click()
    await expect(recipient.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  } finally { await recipientContext.close() }
})

