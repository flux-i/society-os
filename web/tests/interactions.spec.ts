const password = 'Community-preview-2026!'
const verifiedLabel = 'I verified this person’s identity, email and home relationship.'

async function capture(page: Page, name: string) {
  if (!process.env.SOCIETY_CAPTURE_UI) return
  await page.evaluate(() => document.fonts.ready)
  const folder = resolve('../reports/local/interaction-review')
  mkdirSync(folder, { recursive: true, mode: 0o700 })
  const path = resolve(folder, name + '.png')
  await page.screenshot({ path })
  chmodSync(path, 0o600)
}
async function signIn(page: Page, email: string, value: string) {
  await page.getByLabel('Email address', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill(value)
  const response = page.waitForResponse(response => response.url().endsWith('/api/auth/login'))
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  expect((await response).status()).toBe(200)
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toHaveCount(0)
  await completePreviewMFA(page)
  await expect(page.getByRole('button', { name: 'Sign out', exact: true })).toBeVisible()
}
async function prepareInvitation(page: Page, name: string, email: string, role = 'RESIDENT') {
  await page.getByRole('button', { name: 'Invite a person', exact: true }).click()
  await page.getByLabel('Find a person').fill(name)
  await chooseOption(page, 'Person in the registry', name)
  await page.getByLabel('Email address', { exact: true }).fill(email)
  await chooseOption(page, 'Access', role)
  if (role !== 'RESIDENT') await page.getByLabel('Access term (days)').fill('30')
  await page.getByRole('checkbox', { name: verifiedLabel }).check()
  await page.getByLabel('Verification note').fill('Fictional identity verified for isolated interaction QA.')
}
async function issueLink(page: Page) {
  await page.getByRole('button', { name: 'Create personal link', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Their door is open.' })).toBeVisible()
  return page.getByLabel('Personal link', { exact: true }).inputValue()
}

