test('navigation and dialog controls fit tablet, narrow and reduced-height screens', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await login(page)
  for (const viewport of [{ width: 1024, height: 768 }, { width: 768, height: 1024 }, { width: 320, height: 568 }, { width: 375, height: 500 }]) {
    await page.setViewportSize(viewport)
    await page.evaluate(() => window.scrollTo(0, 0))
    if (viewport.width <= 850) {
      await page.getByRole('button', { name: 'Menu', exact: true }).click()
      await page.keyboard.press('Escape')
      await expect(page.getByRole('button', { name: 'Menu', exact: true })).toHaveAttribute('aria-expanded', 'false')
      await page.getByRole('button', { name: 'Menu', exact: true }).click()
      for (const name of ['Overview', 'Homes & people', 'Access & invitations', 'Entries', 'Receipts', 'Requests & approvals', 'Community', 'Help & repairs', 'Account security', 'Documents']) {
        await page.getByRole('link', { name, exact: true }).scrollIntoViewIfNeeded()
        await expect(page.getByRole('link', { name, exact: true })).toBeInViewport({ ratio: 1 })
      }
      await capture(page, `navigation-${viewport.width}x${viewport.height}`)
      await page.getByRole('link', { name: 'Account security', exact: true }).focus()
      await page.keyboard.press('Escape')
      await expect(page.getByRole('button', { name: 'Menu', exact: true })).toBeFocused()
      await expect(page.getByRole('button', { name: 'Menu', exact: true })).toHaveAttribute('aria-expanded', 'false')
    } else {
      await expect(page.locator('.workspace-profile')).toBeInViewport({ ratio: 1 })
      const accessIcon = await page.getByRole('link', { name: 'Access & invitations', exact: true }).locator('svg').boundingBox()
      expect(accessIcon?.width).toBeGreaterThanOrEqual(16)
      await capture(page, `navigation-${viewport.width}x${viewport.height}`)
    }
    await navigate(page, 'Access & invitations')
    await expect(page.getByRole('heading', { name: 'A personal welcome.' })).toBeVisible()
    await page.getByRole('button', { name: 'Invite a person', exact: true }).click()
    await page.locator('.dialog-scroll').evaluate(el => { el.scrollTop = el.scrollHeight })
    await expect(page.getByRole('button', { name: 'Close invitation', exact: true })).toBeInViewport({ ratio: 1 })
    await expect(page.getByRole('button', { name: 'Create personal link', exact: true })).toBeInViewport({ ratio: 1 })
    expect(await page.getByRole('dialog').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await capture(page, `invitation-${viewport.width}x${viewport.height}`)
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: 'Invite a person', exact: true })).toBeFocused()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
})
